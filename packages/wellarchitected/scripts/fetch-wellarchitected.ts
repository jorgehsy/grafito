// Rebuilds src/framework.generated.ts from the live AWS Well-Architected Framework: the general and
// per-pillar design principles, and every question and best-practice title with its ID.
// All or nothing: on any error or failed check it writes nothing.
// Usage: pnpm --filter @grafito/wellarchitected wa:fetch
//
// Pages are read through the public AWS Knowledge MCP server (no auth, no AWS account), not from
// docs.aws.amazon.com directly: it returns each page as clean markdown, so there is no HTML to scrape,
// and it is reachable from sandboxes where docs.aws.amazon.com is blocked. Its markdown has no links,
// so question pages are found by their URL pattern (`rel-10.html`), plus QUESTION_PAGES for the few
// that live elsewhere. The documentation search was tried for those and does not find them reliably.
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { PILLARS } from "../src/pillars";
import type { BestPractice, FetchedFramework, FetchedPillar, PillarId, Question } from "../src/types";

const MCP_ENDPOINT = "https://knowledge-mcp.global.api.aws";
export const FRAMEWORK_BASE = "https://docs.aws.amazon.com/wellarchitected/latest/framework/";
const OUT_FILE = resolve(dirname(fileURLToPath(import.meta.url)), "../src/framework.generated.ts");
// The server's rate limits are not published; one call at a time with a pause between them.
const DELAY_MS = 300;

const PAGES: Record<PillarId, { designPrinciples: string; questionPrefix: string }> = {
  OPS: { designPrinciples: "oe-design-principles", questionPrefix: "ops" },
  SEC: { designPrinciples: "sec-design", questionPrefix: "sec" },
  REL: { designPrinciples: "rel-dp", questionPrefix: "rel" },
  PERF: { designPrinciples: "perf-dp", questionPrefix: "perf" },
  COST: { designPrinciples: "cost-dp", questionPrefix: "cost" },
  SUS: { designPrinciples: "sus-design-principles", questionPrefix: "sus" },
};

// Question pages that are not at `<prefix>-NN.html`. The slug is generated by the docs toolchain and may
// change between framework revisions; the gap check below then names the question to fix here.
const QUESTION_PAGES: Record<string, string> = {
  "SUS 1": "w2aac19c17b7b5",
};

const pageUrl = (slug: string) => `${FRAMEWORK_BASE}${slug}.html`;
const squash = (s: string) => s.replace(/\s+/g, " ").trim();

// Folds markdown bullets with their indented continuation lines into one string per bullet.
function bullets(lines: string[]): string[] {
  const out: string[] = [];
  for (const line of lines) {
    if (line.startsWith("* ")) out.push(line.slice(2));
    else if (/^\s+\S/.test(line) && out.length) out[out.length - 1] += " " + line.trim();
  }
  return out.map(squash);
}

export function parsePublicationDate(md: string): string {
  const m = md.match(/Publication date:\s*\*\*([^*]+)\*\*/);
  if (!m) throw new Error("No publication date on the welcome page");
  return squash(m[1]);
}

/** The bold titles of a design-principles page, e.g. `* **Test recovery procedures**: ...`. */
export function parseDesignPrinciples(md: string): string[] {
  return bullets(md.split("\n"))
    .map((b) => b.match(/^\*\*(.+?)\*\*/)?.[1])
    .filter((t): t is string => !!t)
    .map((t) => squash(t).replace(/:$/, ""));
}

/** Reads a question page (`# REL 10. How do you ...?` plus a `* REL10-BP01 ...` list). */
export function parseQuestionPage(md: string, pillar: PillarId, n: number): Question {
  const heading = md.match(/^# ([A-Z]+) (\d+)\.? (.+)$/m);
  if (!heading || heading[1] !== pillar || Number(heading[2]) !== n) {
    throw new Error(`Expected the page of ${pillar} ${n}, got "${heading?.[0] ?? md.slice(0, 80)}"`);
  }
  const lines = md.split("\n");
  const start = lines.findIndex((l) => /^#+ Best practices\s*$/.test(l));
  if (start < 0) throw new Error(`${pillar} ${n}: no best practices list`);
  const bpPrefix = `${pillar}${String(n).padStart(2, "0")}-BP`;
  const bestPractices: BestPractice[] = bullets(lines.slice(start + 1)).map((b) => {
    const m = b.match(/^([A-Z]+\d{2}-BP\d{2}) (.+)$/);
    if (!m || !m[1].startsWith(bpPrefix)) throw new Error(`${pillar} ${n}: unexpected best practice "${b}"`);
    return { id: m[1], title: m[2] };
  });
  if (!bestPractices.length) throw new Error(`${pillar} ${n}: empty best practices list`);
  return { id: `${pillar} ${n}`, title: squash(heading[3]), bestPractices };
}

export function renderFrameworkModule(data: FetchedFramework): string {
  return [
    "// Generated by scripts/fetch-wellarchitected.ts from the AWS Well-Architected Framework. Do not edit.",
    "// Adapted from AWS documentation, CC BY-SA 4.0; see ../NOTICE.md.",
    'import type { FetchedFramework } from "./types";',
    "",
    `export const FRAMEWORK: FetchedFramework = ${JSON.stringify(data, null, 2)};`,
    "",
  ].join("\n");
}

type ReadResult = { status: string; content?: string; redirected_url?: string | null; truncated?: boolean; error_code?: string | null };

async function callTool<T>(name: string, args: unknown): Promise<T> {
  await new Promise((r) => setTimeout(r, DELAY_MS));
  const res = await fetch(MCP_ENDPOINT, {
    method: "POST",
    headers: { "content-type": "application/json", accept: "application/json, text/event-stream" },
    body: JSON.stringify({ jsonrpc: "2.0", id: 1, method: "tools/call", params: { name, arguments: args } }),
  });
  if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
  const body = (await res.json()) as { result?: { isError?: boolean; content?: { text: string }[] }; error?: unknown };
  const text = body.result?.content?.[0]?.text;
  if (body.error || body.result?.isError || !text) throw new Error(`${name}: ${JSON.stringify(body.error ?? body.result)}`);
  return (JSON.parse(text) as { content: { result: T } }).content.result;
}

/** The page's markdown, or null when it does not exist (a missing framework page redirects to the welcome page). */
async function readPage(url: string): Promise<string | null> {
  const [r] = await callTool<ReadResult[]>("aws___read_documentation", { requests: [{ url, max_length: 50000 }] });
  if (r.status !== "SUCCESS") {
    if (r.error_code === "not_found") return null;
    throw new Error(`${url}: ${r.status} ${r.error_code}`);
  }
  if (r.redirected_url && r.redirected_url !== url) return null;
  if (r.truncated) throw new Error(`${url}: truncated`);
  return r.content ?? "";
}

function questionPageUrl(pillar: PillarId, n: number): string {
  return pageUrl(QUESTION_PAGES[`${pillar} ${n}`] ?? `${PAGES[pillar].questionPrefix}-${String(n).padStart(2, "0")}`);
}

async function required(url: string): Promise<string> {
  const md = await readPage(url);
  if (md === null) throw new Error(`Missing page: ${url}`);
  return md;
}

export async function fetchFramework(log: (s: string) => void = console.log): Promise<FetchedFramework> {
  const publicationDate = parsePublicationDate(await required(pageUrl("welcome")));
  const generalDesignPrinciples = parseDesignPrinciples(await required(pageUrl("general-design-principles")));
  const pillars: FetchedPillar[] = [];
  for (const { id } of PILLARS) {
    const designPrinciples = parseDesignPrinciples(await required(pageUrl(PAGES[id].designPrinciples)));
    const questions: Question[] = [];
    // Questions are numbered from 1 with no gaps, so the pillar ends at the first missing page. The page
    // after it is checked too: if that one exists, a question page has moved (see QUESTION_PAGES).
    for (let n = 1; ; n++) {
      const md = await readPage(questionPageUrl(id, n));
      if (md === null) {
        if ((await readPage(questionPageUrl(id, n + 1))) !== null) {
          throw new Error(`${id} ${n}: no page at ${questionPageUrl(id, n)}, but ${id} ${n + 1} exists; add its URL to QUESTION_PAGES`);
        }
        break;
      }
      questions.push(parseQuestionPage(md, id, n));
    }
    const bps = questions.reduce((sum, q) => sum + q.bestPractices.length, 0);
    log(`${id}: ${designPrinciples.length} design principles, ${questions.length} questions, ${bps} best practices`);
    if (!designPrinciples.length || !questions.length) throw new Error(`${id}: nothing found`);
    pillars.push({ id, designPrinciples, questions });
  }
  if (!generalDesignPrinciples.length) throw new Error("No general design principles");
  return { publicationDate, generalDesignPrinciples, pillars };
}

// Only runs as a command, not when imported from the tests.
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fetchFramework()
    .then((data) => {
      writeFileSync(OUT_FILE, renderFrameworkModule(data));
      console.log(`Done: framework published ${data.publicationDate}, written to ${OUT_FILE}`);
    })
    .catch((e: unknown) => {
      console.error(e instanceof Error ? e.message : e);
      console.error("Nothing was written.");
      process.exit(1);
    });
}
